#!/usr/bin/env bash
#
# Выкатка на staging.
#
# Отдельная команда и отдельная конфигурация. Сервер может быть тем же, что
# у production, но каталог, Compose-проект, внешний порт, том и файл окружения
# обязаны отличаться — иначе команда откажет до обращения к серверу.
#
#   ./deploy/scripts/deploy-staging.sh --version <полный-sha> [--dry-run]

set -euo pipefail

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd -- "${SCRIPT_DIR}/../.." && pwd)"
cd -- "${REPO_ROOT}"

# shellcheck source=deploy/scripts/lib/common.sh
source "${SCRIPT_DIR}/lib/common.sh"

EXPECTED_MARKER="staging"

parse_args "$@"

step "Проверка версии"
require_full_sha
log "версия: ${VERSION}"

CONFIG_FILE="$(staging_config_file)"

if is_dry_run; then
  # Сухой прогон ничего не читает и никуда не ходит: он только печатает план.
  # Конфигурация не открывается вовсе, поэтому прогон работает и на свежем клоне.
  step "Сухой прогон"
  log "режим DRY_RUN: конфигурация не читается, сеть и изменения не выполняются"
  cat <<PLAN

План выкатки на staging:
  1. прочитать ${CONFIG_FILE}
  2. проверить изоляцию от production, если его конфигурация уже создана
  3. проверить маркер окружения в каталоге цели (ожидается «${EXPECTED_MARKER}»)
  4. занять локальный и удалённый deploy lock
  5. загрузить образ ${VERSION} из приватного реестра
  6. сверить OCI-метку org.opencontainers.image.revision с ${VERSION}
  7. проверить подложку по манифесту и пересчитать на сервере SHA-256 обоих
     артефактов графа — tiles.tar И valhalla.json, — сведя их с манифестом,
     с VALHALLA_GRAPH_SHA256 и с бюджетом матрицы обоих профилей
  8. доставить Compose-файл выкатываемой версии и сверить его контрольную сумму
  9. поднять маршрутизатор ОТДЕЛЬНО и дождаться загрузки набора тайлов
 10. посчитать ПРЕДЕЛЬНУЮ матрицу 60×60 на утверждённом дорожном наборе обоими
     профилями и отдельно регрессию пешеходного профиля; пустой элемент, 4xx
     и 5xx останавливают выкатку здесь
 11. проверить артефакты геокодера: сумму photon.jar и непустой индекс
     в версионном каталоге, на который указывает photon/current
 12. поднять геокодер ОТДЕЛЬНО и убедиться, что он не только отвечает
     на /status, но и находит публичный ориентир: пустой индекс отвечает тоже
 13. поднять решатель ОТДЕЛЬНО
 14. проверить решатель пробной задачей с пользовательской матрицей: он обязан
     учитывать время обслуживания по типу машины, иначе выкатка останавливается
     здесь — до миграций и до запуска нового приложения
 15. только после этого применить миграции (prisma migrate deploy)
 16. запустить приложение из точной версии образа
 17. дождаться /ready на внешнем порту staging
 18. записать версию в state/verified-versions и отчитаться о развёрнутом SHA

Изменений не выполнено: это сухой прогон.
PLAN
  exit 0
fi

# Сухой прогон уже завершился выше: дальше идут проверки, требующие git и сети.
require_clean_worktree
require_commit_in_origin_main
log "коммит найден в origin/main, рабочее дерево чистое"

step "Конфигурация окружения"
load_environment_config STAGING "${CONFIG_FILE}"
require_config_values STAGING "${CONFIG_FILE}" "${CONFIG_KEYS[@]}"

# Ошибка в конфигурации не должна привести к выкатке staging-версии на production.
[ "${STAGING_ENVIRONMENT_MARKER}" = "${EXPECTED_MARKER}" ] \
  || fail "конфигурация помечена как «${STAGING_ENVIRONMENT_MARKER}», а это команда staging"

# Изоляция проверяется, как только появилась вторая конфигурация. Пока
# production ещё не настроен, staging разворачивается в одиночку.
PRODUCTION_CONFIG_FILE="$(production_config_file)"
if [ -f "${PRODUCTION_CONFIG_FILE}" ]; then
  load_environment_config PRODUCTION "${PRODUCTION_CONFIG_FILE}"
  require_config_values PRODUCTION "${PRODUCTION_CONFIG_FILE}" "${CONFIG_KEYS[@]}"
  require_isolated_environments
else
  log "конфигурация production ещё не создана: проверка изоляции пропущена"
fi

activate_environment STAGING

step "Подготовка соединения"
prepare_known_hosts
acquire_local_lock "staging"

step "Проверка цели"
require_environment_marker
log "маркер окружения совпал в каталоге ${REMOTE_DIR}"

acquire_remote_lock
trap 'release_remote_lock; release_local_lock' EXIT

step "Загрузка образа"
remote "docker pull '$(image_reference)'"
require_image_revision
log "метка образа соответствует ${VERSION}"

step "Картографические артефакты"
# Fail closed: приложение стартует с подложкой и графом, смонтированными
# на чтение, и обязано получить именно те файлы, которые собирали.
require_geo_artifacts

step "Состав окружения"
# Compose-файл обязан соответствовать выкатываемой версии: он описывает состав
# сервисов и монтирования, и файл произвольного возраста означал бы запуск
# не того окружения, которое проверял CI.
sync_compose_file

step "Запуск маршрутизатора"
# Маршрутизатор поднимается ПЕРВЫМ и отдельно от приложения — и до миграций.
#
# Одновременный запуск с приложением выглядит быстрее, но приложение опрашивает
# /status сразу при старте: пока граф загружается, оно успевает записать
# DEGRADED, и это состояние осталось бы в базе даже после того, как выкатка
# убедится, что маршрутизатор работает. Логист видел бы «расчёт недоступен»
# при исправном сервисе.
remote "$(compose_command) up -d --no-build valhalla"

step "Проверка маршрутизатора"
# Отказ здесь останавливает выкатку до миграций: схема остаётся прежней,
# новый app не запускается вовсе, прежняя версия продолжает работать.
require_routing_ready

step "Артефакты геокодера"
# Fail closed: приложение стартует с индексом, смонтированным на чтение,
# и обязано получить именно тот набор, который собирали отдельно. Индекс
# на сервере НЕ собирается: он приезжает готовым неизменяемым артефактом.
require_photon_artifacts

step "Запуск геокодера"
# Геокодер поднимается отдельно и ДО приложения по той же причине, что
# маршрутизатор и решатель: приложение опрашивает его при старте, и «ещё
# не поднялся» осталось бы в базе как «недоступен» при исправном сервисе.
remote "$(compose_command) up -d --no-build photon"

step "Проверка геокодера"
# Отказ здесь останавливает выкатку до миграций: прежняя версия продолжает
# работать, схема остаётся прежней.
require_photon_ready

step "Запуск решателя"
# Решатель поднимается отдельно и до приложения по той же причине, что
# и маршрутизатор: приложение проверяет его при старте, и «ещё не поднялся»
# осталось бы в базе как «недоступен» при исправном сервисе.
remote "$(compose_command) up -d --no-build vroom"

step "Проверка решателя"
# Отказ здесь останавливает выкатку до миграций: прежняя версия продолжает
# работать, схема остаётся прежней.
require_solver_ready

step "Миграции"
# Миграции выполняются ПОСЛЕ проверок маршрутизатора и до запуска приложения.
#
# Порядок не косметический. Выкатка устроена так, что при отказе продолжает
# работать прежняя версия — тот же контейнер, та же схема. Применить миграции
# раньше проверок значило бы менять схему под работающим старым приложением
# ради версии, которая может и не запуститься. Поэтому схема меняется только
# после того, как всё, что могло отказать раньше, уже прошло, а сами миграции
# остаются совместимыми с прежней версией: расширение без переименований
# и удалений.
#
# Секреты лежат в файле окружения на сервере и не передаются аргументами команды.
remote "$(compose_command) run --rm app npx prisma migrate deploy"

step "Запуск приложения"
remote "$(compose_command) up -d --no-build app"

step "Проверка готовности"
require_ready

# Отметка о проверенной версии: production принимает только то, что прошло staging.
# Файл лежит в staging-каталоге — именно он служит доказательством.
remote "mkdir -p '${REMOTE_DIR}/state' && echo '${VERSION}' >> '${REMOTE_DIR}/state/verified-versions'"

report_deployed_revision
