-- Знак начального долга на уровне базы.
--
-- Правило знака продублировано в SQL намеренно: код может ошибиться, база — нет.
-- Начальный долг увеличивает долг курьера перед компанией, поэтому он переходит
-- в список «плюсовых» видов наравне с наличными и выдачей денег курьеру.
--
-- Значение `OPENING_DEBT` добавлено ОТДЕЛЬНОЙ предыдущей миграцией не случайно:
-- PostgreSQL запрещает использовать новое значение перечисления в той же
-- транзакции, где оно объявлено, а это ограничение ссылается на него литералом.
-- Поэтому шага ровно два, и порядок между ними обязателен.
--
-- Существующие строки не переписываются и не пересчитываются: у прежних видов
-- знак не меняется, новому ограничению они удовлетворяют так же, как старому.
--
-- Откат: вернуть прежнее ограничение можно, пока в таблице нет строк
-- `OPENING_DEBT`; после их появления прежнее ограничение их отвергнет, и откат
-- выполняется движением вперёд, без удаления финансовых записей.
ALTER TABLE "CourierLedgerEntry"
  DROP CONSTRAINT "CourierLedgerEntry_sign_matches_kind";

ALTER TABLE "CourierLedgerEntry"
  ADD CONSTRAINT "CourierLedgerEntry_sign_matches_kind"
  CHECK (
    "kind" = 'ADJUSTMENT'
    OR ("kind" IN ('CASH_RECEIVED', 'CASH_ISSUED_TO_COURIER', 'OPENING_DEBT') AND "amountMinor" > 0)
    OR ("kind" NOT IN ('CASH_RECEIVED', 'CASH_ISSUED_TO_COURIER', 'OPENING_DEBT') AND "amountMinor" < 0)
  );
