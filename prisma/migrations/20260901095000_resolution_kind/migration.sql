-- Задача логиста бывает не только про недоставку.
--
-- Отмена, пришедшая из МоегоСклада уже ПОСЛЕ доставки, меняет не товар, а
-- бумаги: букет у клиента, деньги, возможно, получены. Автоматически такой
-- заказ не трогается — появляется задача на коррекцию, и решает её человек.
-- Прежние задачи остаются недоставками: значение по умолчанию совпадает
-- с тем, чем они были.
CREATE TYPE "OrderResolutionKind" AS ENUM ('FAILED_DELIVERY', 'CANCELLED_AFTER_DELIVERY');

ALTER TABLE "OrderResolution"
  ADD COLUMN "kind" "OrderResolutionKind" NOT NULL DEFAULT 'FAILED_DELIVERY';

-- Решение «разобрано» закрывает задачу, ничего не меняя в заказе. Оно нужно
-- ровно там, где система не вправе действовать сама.
ALTER TYPE "OrderResolutionDecision" ADD VALUE 'ACKNOWLEDGED';

-- Участие в маршруте иногда закрывает не человек.
--
-- Заказ, у которого сняли отмену, обязан вернуться в «Сделки»
-- нераспределённым: за время отмены день ушёл вперёд, и прежний маршрут
-- восстанавливать нельзя. Решение принимает проход импорта, у него нет
-- автора, и записать сюда чьё-то имя значило бы приписать человеку чужое
-- действие.
ALTER TYPE "RouteOrderRemovalReason" ADD VALUE 'SOURCE_CANCELLATION_WITHDRAWN';
