-- Роль «Управляющий»: операционный администратор без доступа к настройкам.
--
-- Миграция РАСШИРЯЮЩАЯ и ничего не переписывает: добавляется одно значение
-- перечисления. Существующие значения, их порядок и строки `UserRole` не
-- меняются, ни одному пользователю роль не назначается.
--
-- Значение добавляется в КОНЕЦ: PostgreSQL хранит порядок объявления, и вставка
-- в середину сдвинула бы сортировку существующих значений.
--
-- `IF NOT EXISTS` делает повторное применение безвредным.
--
-- ВАЖНО про откат. Предыдущая версия приложения продолжает работать после этой
-- миграции: она не назначает новую роль, поэтому старый код никогда не встретит
-- неизвестное значение в данных. Удалять значение перечисления PostgreSQL не
-- умеет, и обратной миграции у этого шага нет по устройству СУБД.
ALTER TYPE "Role" ADD VALUE IF NOT EXISTS 'SUPERVISOR';
