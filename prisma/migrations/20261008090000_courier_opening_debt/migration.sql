-- Начальный долг курьера: долг перед компанией, существовавший до перехода на ERP.
--
-- Миграция РАСШИРЯЮЩАЯ и ничего не переписывает: добавляется одно значение
-- перечисления. Существующие значения, их порядок и строки `CourierLedgerEntry`
-- не меняются, ни одному курьеру долг не начисляется.
--
-- Значение добавляется в КОНЕЦ: PostgreSQL хранит порядок объявления, и вставка
-- в середину сдвинула бы сортировку существующих значений.
--
-- `IF NOT EXISTS` делает повторное применение безвредным.
--
-- ВАЖНО про откат. Удалять значение перечисления PostgreSQL не умеет, обратной
-- миграции у этого шага нет по устройству СУБД. Прежний образ приложения
-- безопасен ТОЛЬКО пока в данных нет записей `OPENING_DEBT`: старый код их не
-- создаёт, но, читая журнал, встретил бы неизвестное значение. Поэтому ПОСЛЕ
-- появления первых записей `OPENING_DEBT` совместимость прежнего образа больше
-- не гарантируется, и откат выполняется движением ВПЕРЁД (новый образ с
-- исправлением). Откат не должен требовать удаления финансовых записей или
-- наката старого дампа поверх новых данных: журнал неизменяем, ошибочная запись
-- исправляется обратной записью.
ALTER TYPE "CourierLedgerKind" ADD VALUE IF NOT EXISTS 'OPENING_DEBT';
