-- Ожидающая подтверждения версия производственного снимка.
--
-- ПОЧЕМУ ОТДЕЛЬНАЯ МИГРАЦИЯ, А НЕ ПРАВКА ПРЕДЫДУЩЕЙ.
-- `20260820090000_florist_order_content` уже применена (локальные проверочные
-- базы) и опубликована в ветке. Правило forward-only не делает исключения для
-- «ещё не смерженной» миграции: исправление оформляется новой. Имя выбрано
-- между зарезервированными слотами FLORIST (`…090000`) и WAREHOUSE
-- (`…091000_storage_cells`), чтобы не занять чужой номер.
--
-- ЧТО ИСПРАВЛЯЕТСЯ.
-- Предыдущая версия кода при недоступных позициях записывала новый
-- `description` и «Текст открытки» прямо в подтверждённые поля, оставляя
-- прежние хеш, позиции и ревизию. Получалась строка из двух внешних версий
-- сразу: тексты новые, состав старый, хеш от старого. Подтверждённый снимок
-- по контракту — тексты И состав вместе, поэтому ожидающие подтверждения
-- данные обязаны жить отдельно.
--
-- Миграция РАСШИРЯЮЩАЯ: три nullable-колонки, замена одного CHECK на более
-- строгий и одно обновление служебной строки курсора. Ни одна колонка
-- не удаляется и не меняет тип.

ALTER TABLE "DeliveryOrder"
  ADD COLUMN "fulfillmentPendingDescription"     TEXT,
  ADD COLUMN "fulfillmentPendingCardText"        TEXT,
  ADD COLUMN "fulfillmentPendingExternalUpdated" TIMESTAMP(3);

-- ИНВАРИАНТ `READY`.
--
-- `READY` означает «подтверждённый снимок есть и он целиком актуален». Значит,
-- в этом состоянии не может остаться ни ожидающей версии, ни кода отказа:
-- иначе строка одновременно утверждала бы «всё подтверждено» и «есть
-- неприменённая версия», и любой читатель был бы вправе поверить любому из двух.
--
-- Прежняя гарантия hash/syncedAt сохраняется целиком — новый CHECK включает её.
--
-- Ограничение безопасно применяется к существующим строкам: новые колонки
-- только что созданы со значением NULL, а `READY` до этой миграции могли
-- получить лишь строки, у которых hash и syncedAt уже заполнены проверкой
-- предыдущей миграции.
ALTER TABLE "DeliveryOrder"
  DROP CONSTRAINT "DeliveryOrder_fulfillment_ready_has_snapshot";

ALTER TABLE "DeliveryOrder"
  ADD CONSTRAINT "DeliveryOrder_fulfillment_ready_is_complete"
  CHECK (
    "fulfillmentCompositionState" <> 'READY'
    OR (
      "fulfillmentSnapshotHash" IS NOT NULL
      AND "fulfillmentCompositionSyncedAt" IS NOT NULL
      AND "fulfillmentCompositionFailure" IS NULL
      AND "fulfillmentPendingDescription" IS NULL
      AND "fulfillmentPendingCardText" IS NULL
      AND "fulfillmentPendingExternalUpdated" IS NULL
    )
  );

-- ПОВТОРНАЯ ПОЛНАЯ ЗАГРУЗКА ПРОИЗВОДСТВЕННОЙ ОБЛАСТИ.
--
-- Тексты снимка приходят только вместе с документом заказа. Заказы, уже лежащие
-- в базе до появления состава, документа в новом коде ещё не видели: у них нет
-- ни подтверждённых текстов, ни ожидающих. Очередь дозагрузки читает только
-- позиции и текстов взять неоткуда — она подтвердила бы снимок с пустыми
-- `description` и «Текстом открытки», то есть записала бы в неизменяемую
-- историю неправду.
--
-- Delta такие заказы не принесёт: она возвращает только изменившиеся документы.
-- Поэтому признак полной загрузки производственной области сбрасывается, и
-- ближайший проход перечитывает заказы утверждённого склада целиком — вместе
-- с текстами и вложенным составом, без единого дополнительного запроса на заказ.
--
-- Это тот же путь, что уже используется при переходе с узкой логистической
-- загрузки на широкую производственную: `updatedCursor` он не сдвигает, потому
-- что первоначальная загрузка уже была завершена ранее.
UPDATE "IntegrationCursor"
SET "fulfillmentLoadCompleted" = false,
    "fulfillmentLoadCompletedAt" = NULL
WHERE "provider" = 'moysklad';
