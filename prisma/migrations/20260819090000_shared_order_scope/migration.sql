-- Производственная область заказа и признак её первоначальной загрузки.
--
-- Миграция РАСШИРЯЮЩАЯ: добавляются только колонки со значениями по умолчанию
-- и один индекс. Ни одна существующая колонка не удаляется, не переименовывается
-- и не меняет тип; перечисления не пересоздаются; старые миграции не тронуты.
--
-- ПОЧЕМУ ДВА ПРИЗНАКА, А НЕ ОДИН ИЗМЕНЁННЫЙ.
--
-- `inScope` сохраняет ровно прежний смысл (склад + «Доставка» + не архивирован):
-- на него опираются экраны логиста, маршрутизация, планирование, конфликты
-- и геокодирование. Производственная область шире — тот же склад и любой способ
-- получения, — поэтому она выражается отдельной колонкой, а не переопределением
-- существующей.
--
-- ЗАСЫПКА СУЩЕСТВУЮЩИХ СТРОК.
--
-- Всё, что сейчас в логистической области, обязано оказаться и в производственной:
-- она строго шире. Обратное неверно, поэтому остальные строки здесь не трогаются —
-- их дочитывает обязательный расширенный первоначальный проход, который читает
-- заказы утверждённого склада без фильтра по способу получения.
--
-- Значение по умолчанию `false` безопасно: неизвестная строка не попадает
-- в производственные выборки, пока её не подтвердит импорт.
ALTER TABLE "DeliveryOrder"
  ADD COLUMN "fulfillmentInScope" BOOLEAN NOT NULL DEFAULT false;

UPDATE "DeliveryOrder" SET "fulfillmentInScope" = true WHERE "inScope" = true;

CREATE INDEX "DeliveryOrder_fulfillmentInScope_deliveryDate_idx"
  ON "DeliveryOrder" ("fulfillmentInScope", "deliveryDate");

-- Признак завершения расширенной загрузки.
--
-- На уже работающей базе `initialLoadCompleted` относится к УЗКОМУ фильтру.
-- Отдельный признак заставляет первый проход после обновления дочитать заказы
-- утверждённого склада целиком. Значение по умолчанию `false` означает
-- «ещё не читали» и для чистой базы, и для существующей; чистая база закрывает
-- оба признака одним проходом.
ALTER TABLE "IntegrationCursor"
  ADD COLUMN "fulfillmentLoadCompleted" BOOLEAN NOT NULL DEFAULT false,
  ADD COLUMN "fulfillmentLoadCompletedAt" TIMESTAMP(3);
