-- Счётчик событий роста оплаченной суммы.
--
-- Ключ задания на корректировку наличных состоял из заказа и величины оплаты,
-- а выполненные сообщения очереди не удаляются — значит ключ занимался
-- навсегда. Последовательность «оплата 2000 → отмена результата → новая
-- доставка → снова оплата 2000» не ставила второго задания: за новой доставкой
-- оставались все 5000 наличных вместо 3000.
--
-- Счётчик, а не момент времени: два события обязаны различаться и тогда, когда
-- часы отдали одно значение. Растёт ТОЛЬКО на росте оплаты, поэтому повторный
-- импорт одного снимка номера не меняет и новых денег не создаёт.
--
-- Существующим заказам ставится 0: их прежние задания уже выполнены, а первое
-- новое событие получит номер 1 — он ни с чем не пересекается, потому что
-- прежний ключ номера не содержал вовсе.
ALTER TABLE "DeliveryOrder"
  ADD COLUMN "paymentSyncCount" INTEGER NOT NULL DEFAULT 0;

-- Отрицательного числа событий не бывает.
ALTER TABLE "DeliveryOrder"
  ADD CONSTRAINT "DeliveryOrder_payment_sync_count_non_negative" CHECK ("paymentSyncCount" >= 0);
