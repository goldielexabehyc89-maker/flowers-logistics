-- Идентичность дорожного графа определяется содержимым, а не временем файла.
--
-- Прежде идентичностью считалось Unix-время изменения tiles.tar: оно менялось
-- при обычном копировании набора на сервер и не менялось при подмене
-- содержимого с сохранённым временем. Теперь идентичность — SHA-256 файла.
--
-- Миграция ТОЛЬКО расширяющая (expand). Переименования и удаления здесь нет
-- намеренно.
--
-- Выкатка устроена так, что при отказе запуска новой версии продолжает
-- работать прежняя — тот же контейнер, та же схема. Переименование колонки
-- сделало бы этот запасной путь ловушкой: миграции применились бы, новая
-- версия не поднялась бы, а старая получила бы «column does not exist»
-- на каждом расчёте. Схема обязана оставаться пригодной обеим версиям,
-- пока хоть одна из них может продолжить работу.
--
-- Удаление "graphRevision" — отдельная contract-миграция, после того как все
-- окружения гарантированно обновлены.

-- Новая колонка допускает NULL: предыдущая версия приложения вставляет строки,
-- не зная о ней. Ограничение формата пропускает NULL по той же причине,
-- а непустое значение обязано быть SHA-256 в нижнем регистре.
ALTER TABLE "RouteMatrixCache" ADD COLUMN "graphSha256" TEXT;

ALTER TABLE "RouteMatrixCache"
  ADD CONSTRAINT "RouteMatrixCache_graphSha256_format"
  CHECK ("graphSha256" IS NULL OR "graphSha256" ~ '^[0-9a-f]{64}$');

-- Строки, посчитанные прежней версией, остаются нетронутыми: это её кэш,
-- и она продолжает им пользоваться. Для новой версии они невидимы — она
-- выбирает записи только по "graphSha256", а у них он пуст. Отдельно их
-- удалять незачем: истечёт срок годности, и обычная уборка их заберёт.
CREATE INDEX "RouteMatrixCache_graphSha256_idx" ON "RouteMatrixCache" ("graphSha256");
