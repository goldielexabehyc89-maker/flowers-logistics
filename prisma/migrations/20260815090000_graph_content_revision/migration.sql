-- Идентичность дорожного графа определяется содержимым, а не временем файла.
--
-- Прежде в кэше матриц хранилась «ревизия графа» — Unix-время изменения
-- tiles.tar. Оно меняется при обычном копировании набора на сервер и не
-- меняется при подмене содержимого с сохранённым временем, поэтому не различало
-- разные графы и различало одинаковые. Теперь колонка хранит SHA-256 файла
-- tiles.tar, а ограничение не даёт числовому времени вернуться в неё молча.

-- Кэш очищается целиком.
--
-- Существующие строки посчитаны под прежним смыслом идентичности: их ключи
-- построены по времени файла. Оставить их — значит отдавать расчёты, про
-- которые больше нельзя сказать, по какому графу они получены. Это кэш:
-- потеря строк стоит одного пересчёта, а неверная строка — неверного маршрута.
DELETE FROM "RouteMatrixCache";

ALTER TABLE "RouteMatrixCache" RENAME COLUMN "graphRevision" TO "graphSha256";

ALTER TABLE "RouteMatrixCache"
  ADD CONSTRAINT "RouteMatrixCache_graphSha256_format"
  CHECK ("graphSha256" ~ '^[0-9a-f]{64}$');
