-- Роли производственного контура: флорист и менеджер выдачи.
--
-- Миграция РАСШИРЯЮЩАЯ и ничего не переписывает: добавляются только два значения
-- перечисления. Существующие значения, их порядок и строки `UserRole` не меняются,
-- ни одному пользователю новые роли не назначаются.
--
-- Значения добавляются в КОНЕЦ: PostgreSQL хранит порядок объявления, и вставка
-- в середину сдвинула бы сортировку существующих значений.
--
-- `IF NOT EXISTS` делает повторное применение безвредным. Штатно повтора не будет —
-- Prisma ведёт журнал применённых миграций, — но безопасность здесь дешевле
-- рассуждения о том, что журнал не мог разъехаться.
--
-- ВАЖНО про откат. Предыдущая версия приложения продолжает работать после этой
-- миграции: она не назначает новые роли, поэтому старый код никогда не встретит
-- неизвестное значение в данных. Удалять значение перечисления PostgreSQL не умеет,
-- и обратной миграции у этого шага нет по устройству СУБД.
ALTER TYPE "Role" ADD VALUE IF NOT EXISTS 'FLORIST';

ALTER TYPE "Role" ADD VALUE IF NOT EXISTS 'MANAGER';
