-- Корректировка наличных после оплаты заказа в МоемСкладе.
--
-- Когда оплаченная сумма заказа растёт уже ПОСЛЕ доставки, наличных, которые
-- курьер должен сдать, становится меньше. Исходное начисление при этом не
-- переписывается и не удаляется: появляется связанная корректирующая запись
-- с минусом, привязанная к тому же заказу и той же попытке доставки.
--
-- Значение добавляется в КОНЕЦ перечисления: PostgreSQL хранит порядок
-- объявления, и вставка в середину сдвинула бы сортировку существующих
-- значений. `IF NOT EXISTS` делает повторное применение безвредным.
--
-- Отдельная миграция для ограничения знака НЕ нужна: проверка
-- `CourierLedgerEntry_sign_matches_kind` уже требует минус от любого вида,
-- которого нет в списке «плюсовых», а корректировка наличных именно минусовая.
--
-- ВАЖНО про откат: удалять значение перечисления PostgreSQL не умеет. Прежний
-- образ безопасен, пока в данных нет записей `CASH_PAYMENT_CORRECTION`; после
-- их появления откат выполняется движением вперёд и не требует удаления
-- финансовых записей или наката старого дампа поверх новых данных.
ALTER TYPE "CourierLedgerKind" ADD VALUE IF NOT EXISTS 'CASH_PAYMENT_CORRECTION';
