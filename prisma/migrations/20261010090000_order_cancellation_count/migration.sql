-- Счётчик отмен заказа в источнике.
--
-- Отмену в МоемСкладе снимают и ставят заново: заказ возвращается в работу и
-- успевает получить новые деньги. Каждое событие отмены обязано получить СВОЁ
-- задание на снятие финансового результата — иначе ключ задания оказывается
-- занят навсегда (сообщения очереди не удаляются), и второе снятие не
-- выполняется никогда.
--
-- Счётчик, а не момент времени: два события обязаны различаться и тогда, когда
-- часы отдали одно значение. И счётчик, а не подсчёт заданий по префиксу
-- ключа: такой подсчёт — префиксный LIKE по вечно растущей таблице, для
-- которого индекса не существует, и выполнялся бы он под блокировкой строки
-- заказа внутри транзакции импорта.
--
-- Существующим заказам ставится 0: их прежние задания уже выполнены, а первая
-- новая отмена получит номер 1 — он ни с чем не пересекается, потому что
-- прежний ключ номера не содержал вовсе.
ALTER TABLE "DeliveryOrder"
  ADD COLUMN "cancellationCount" INTEGER NOT NULL DEFAULT 0;

-- Отрицательного числа отмен не бывает.
ALTER TABLE "DeliveryOrder"
  ADD CONSTRAINT "DeliveryOrder_cancellation_count_non_negative" CHECK ("cancellationCount" >= 0);
