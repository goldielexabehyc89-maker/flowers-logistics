-- Отметка снятия финансового результата попытки.
--
-- Снятие признавалось по обратным записям: «все начисления попытки погашены и
-- среди отмен есть отмена заказа». У попытки, обнулённой ДО отмены заказа,
-- сторнировать было нечего — обратных записей не появлялось, и после снятия
-- отмены правка километров снова заводила деньги. Событие отмены не должно
-- зависеть от того, нашлась ли ненулевая проводка.
--
-- Прежним попыткам остаётся NULL: для них снятие по-прежнему опознаётся по
-- причине обратной записи, а неизвестная причина трактуется как возможное
-- снятие — молча возвращать снятые деньги нельзя.
ALTER TABLE "DeliveryAttempt"
  ADD COLUMN "financeStrippedAt" TIMESTAMP(3);
