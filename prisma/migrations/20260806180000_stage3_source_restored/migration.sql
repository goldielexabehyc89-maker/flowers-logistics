-- Причина ревизии «заказ найден снова».
--
-- Восстановление после контрольной сверки отличается от обычного изменения:
-- заказ пропадал не потому, что менялись данные, а потому что отсутствовал
-- в выборке. Отдельная причина делает историю читаемой.

ALTER TYPE "OrderRevisionReason" ADD VALUE IF NOT EXISTS 'SOURCE_RESTORED' AFTER 'SOURCE_MISSING';
