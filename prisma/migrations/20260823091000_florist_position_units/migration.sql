-- Единица измерения количества в производственном составе.
--
-- Миграция РАСШИРЯЮЩАЯ и forward-only: четыре nullable-колонки, ни одна
-- существующая колонка не удаляется, не переименовывается и не меняет тип,
-- перечисления не пересоздаются, данные не переписываются.
--
-- ПОЧЕМУ NULLABLE, А НЕ «ШТ.» ПО УМОЛЧАНИЮ.
-- У номенклатуры единицы может не быть вовсе, а справочник может оказаться
-- недоступным в момент прохода. Подставленная по умолчанию «шт.» выглядела бы
-- как подтверждённый факт и увела бы сборку: «2» и «2 шт.» — разные указания,
-- когда на самом деле это метры. Пустая единица честнее: карточка и бланк
-- покажут одно число, а следующий успешный проход создаст ревизию
-- с заполненной единицей.
--
-- ПОЧЕМУ ДВА ПОЛЯ, А НЕ ССЫЛКА.
-- UUID стабилен, а обозначение в каталоге переименовывают. Бланк обязан
-- печататься тем же, чем печатался, поэтому обозначение замораживается рядом
-- с идентификатором, а не подтягивается из каталога при показе.
--
-- Прежнее приложение о новых колонках не знает и продолжает импортировать
-- и читать заказы: колонки nullable и в его выборки не входят.

ALTER TABLE "DeliveryOrderPosition"
  ADD COLUMN "uomId"   UUID,
  ADD COLUMN "uomName" TEXT;

ALTER TABLE "DeliveryOrderPositionComponent"
  ADD COLUMN "uomId"   UUID,
  ADD COLUMN "uomName" TEXT;
