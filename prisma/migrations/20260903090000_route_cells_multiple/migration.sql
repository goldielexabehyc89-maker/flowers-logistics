-- У маршрутного листа может быть несколько маршрутных ячеек.
--
-- Прежнее правило «одна активная ячейка на лист» держалось частичным
-- уникальным индексом. Оно оказалось уже физики склада: в лист входит
-- полтора десятка коробок, они не помещаются на одну полку, и кладовщику
-- приходилось выбирать между «положить мимо листа» и «не собрать лист».
--
-- Второе правило снимать НЕЛЬЗЯ и оно остаётся: одна полка не может
-- одновременно принадлежать двум активным листам, иначе на ней встретятся
-- коробки двух курьеров и разъедутся не туда.
DROP INDEX "RouteCellBinding_active_route_unique";

-- Одна и та же ячейка не привязывается к одному листу дважды.
--
-- Повторное назначение той же ячейки должно быть идемпотентным, а не
-- создавать вторую действующую привязку: иначе «освободить ячейку»
-- пришлось бы выполнять столько раз, сколько её случайно отсканировали.
CREATE UNIQUE INDEX "RouteCellBinding_active_route_cell_unique"
  ON "RouteCellBinding" ("routeId", "cellId") WHERE "releasedAt" IS NULL;
