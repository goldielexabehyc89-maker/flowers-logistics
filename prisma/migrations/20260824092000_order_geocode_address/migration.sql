-- Запрос к геокодеру отдельно от операционного адреса.
--
-- Адрес заказа операционный: в нём квартира, подъезд и домофон, без которых
-- курьер не доедет. Геокодеру они мешают — он ищет дом, а не квартиру в нём,
-- и лишние слова уводят поиск. Одно поле обслужить оба назначения не может,
-- поэтому их два.
--
-- NULL означает «отдельного запроса нет»: геокодер берёт адрес заказа, как
-- и раньше. Миграция расширяющая: колонка добавляется пустой, существующие
-- строки не переписываются, а прежняя версия приложения её не читает
-- и продолжает работать против расширенной схемы.
ALTER TABLE "DeliveryOrder" ADD COLUMN "geocodeAddress" TEXT;

COMMENT ON COLUMN "DeliveryOrder"."geocodeAddress" IS
  'Строка запроса к геокодеру, собранная из разобранного адреса. NULL — используется address.';
