-- Причина внимания: адреса для геокодера недостаточно.
--
-- «Адреса нет» и «адрес есть, но геокодеру его мало» — разные состояния,
-- и человеку нужно видеть, какое именно. У заказа может быть заполнена строка
-- `address`, а разобранных улицы и дома в источнике не оказаться: искать по
-- такой строке автоматически мы больше не пробуем, и заказ ждёт человека.
--
-- Значение добавляется В КОНЕЦ перечисления. PostgreSQL хранит порядок
-- объявления, и вставка в середину сдвинула бы уже записанные строки.
-- Миграция расширяющая: существующие строки не переписываются, прежняя версия
-- приложения нового значения просто не встретит.
ALTER TYPE "OrderAttentionReason"
  ADD VALUE IF NOT EXISTS 'GEOCODING_ADDRESS_INCOMPLETE';
