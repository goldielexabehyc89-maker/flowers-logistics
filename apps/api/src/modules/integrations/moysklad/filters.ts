/**
 * Выражения фильтра МоегоСклада.
 *
 * Условия собираются обычными строками и соединяются `;` внутри одного параметра
 * `filter`. Кодирование выполняется ровно один раз — в `URLSearchParams` клиента.
 * Ручное кодирование частей дало бы двойное кодирование, и ссылка перестала бы
 * совпадать с идентификатором на стороне МоегоСклада.
 *
 * Область запросов различается намеренно:
 *  * полная загрузка (первоначальная и контрольная сверка) сужает выборку на сервере
 *    по утверждённому складу и нижней границе даты, но НЕ по способу получения:
 *    самовывоз того же склада относится к производственной области, и фильтр по
 *    способу оставил бы его непрочитанным навсегда;
 *  * delta-проход фильтрует ТОЛЬКО по `updated`. Фильтруй он по складу или способу,
 *    заказ, перенесённый на другой склад, исчез бы из выборки, и система никогда
 *    не узнала бы, что он вышел из нашей области.
 */

import { MOYSKLAD_BASE_URL, type MOYSKLAD_IDS } from './config.js';
import { formatMoscow } from './moscow-time.js';

type Ids = typeof MOYSKLAD_IDS;

const entity = (kind: string, id: string): string => `${MOYSKLAD_BASE_URL}/entity/${kind}/${id}`;

/**
 * Формат даты и времени МоегоСклада — всегда московское время.
 * Отправленное в UTC значение сдвинуло бы окно на три часа, и синхронизация
 * молча отставала бы. Пробел закодирует URLSearchParams.
 */
export function formatMoment(date: Date): string {
  return formatMoscow(date);
}

/**
 * Фильтр полной выборки: утверждённый склад и нижняя граница плановой даты.
 * Верхней границы нет — будущие заказы нужны целиком.
 *
 * Способ получения в фильтр НЕ входит намеренно. Область производства — это тот
 * же склад при любом способе получения, поэтому серверный фильтр по «Доставке»
 * скрыл бы самовывоз от первоначальной загрузки и от контрольной сверки:
 * первый остался бы непрочитанным, а второй объявил бы его пропавшим.
 * По статусу не фильтруем: он ничего не решает о принадлежности заказа.
 *
 * Разделение на логистическую и производственную область выполняет mapper по
 * уже прочитанному заказу, а не сервер МоегоСклада.
 */
export function approvedStoreFilter(ids: Ids, since: Date, cutoff?: string | undefined): string {
  return [
    `store=${entity('store', ids.store)}`,
    `deliveryPlannedMoment>=${formatMoment(lowerBound(since, cutoff))}`,
  ].join(';');
}

/**
 * Нижняя граница выборки: позднейшая из окна прохода и границы отбора.
 *
 * Сужение на стороне МоегоСклада — это экономия страниц, а не защита: delta
 * ходит по окну `updated` и приносит заказы с любой датой. Не создать старый
 * заказ обязан импорт (`beforeImportCutoff`), и он это делает независимо
 * от того, что вернул чужой API.
 *
 * Полночь считается МОСКОВСКАЯ: `deliveryPlannedMoment` сравнивается
 * МоимСкладом в московском времени, и полночь UTC сдвинула бы границу
 * на три часа — заказ на самой границе то попадал бы в выборку, то нет.
 */
function lowerBound(since: Date, cutoff: string | undefined): Date {
  if (cutoff === undefined) {
    return since;
  }
  const match = /^(\d{4})-(\d{2})-(\d{2})$/.exec(cutoff);
  if (match === null) {
    // Значение уже проверено разбором конфигурации; сюда попасть нельзя,
    // но молча расширять выборку при неожиданном формате нельзя тем более.
    return since;
  }
  const moscowMidnightUtc =
    Date.UTC(Number(match[1]), Number(match[2]) - 1, Number(match[3])) - 3 * 60 * 60 * 1000;
  const bound = new Date(moscowMidnightUtc);
  return bound.getTime() > since.getTime() ? bound : since;
}

/**
 * Фильтр delta-прохода: конечное окно по `updated`.
 *
 * Верхняя граница обязательна — без неё окно росло бы вместе с потоком изменений,
 * и проход никогда не заканчивался бы на активном аккаунте.
 */
export function deltaFilter(from: Date, to: Date): string {
  return [`updated>=${formatMoment(from)}`, `updated<=${formatMoment(to)}`].join(';');
}
