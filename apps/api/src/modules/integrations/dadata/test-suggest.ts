/**
 * Подменённый HTTP подсказок адреса.
 *
 * ЧЕСТНО О ГРАНИЦЕ. Это не DaData и не геокодер. Он отвечает фиксированным
 * набором адресов в формате провайдера, чтобы браузерная приёмка проходила
 * через НАСТОЯЩИЙ серверный контракт: тот же эндпоинт, тот же разбор ответа,
 * те же правила «что считать точной привязкой».
 *
 * Живого ключа в проверках нет и быть не должно, а без ответа проверять
 * нечего: экран показал бы «подсказки не настроены» и остановился.
 *
 * Fail closed: включается только явным флагом и только в локальном окружении.
 */

/** Дом с точкой: такую подсказку экран принимает. */
const EXACT_HOUSE = {
  value: 'г Москва, ул Цветочная, д 1',
  data: { geo_lat: '55.751244', geo_lon: '37.618423', qc_geo: '0' },
};

/** Улица без дома: координаты есть, но привязка не точная — принимать нельзя. */
const STREET_ONLY = {
  value: 'г Москва, ул Цветочная',
  data: { geo_lat: '55.750000', geo_lon: '37.610000', qc_geo: '2' },
};

/**
 * Фиксированный ответ в формате DaData.
 *
 * Запрос не разбирается: набор один и тот же. Проверяется поведение экрана
 * и сервера, а не качество поиска.
 */
export function testSuggestFetch(): typeof globalThis.fetch {
  return (async () =>
    new Response(JSON.stringify({ suggestions: [EXACT_HOUSE, STREET_ONLY] }), {
      status: 200,
      headers: { 'content-type': 'application/json' },
    })) as unknown as typeof globalThis.fetch;
}
