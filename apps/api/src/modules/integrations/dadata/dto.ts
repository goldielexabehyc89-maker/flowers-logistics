/**
 * Проверенная часть ответа стандартизации DaData.
 *
 * Берутся только три официальных поля: `geo_lat`, `geo_lon` и `qc_geo`.
 * Остальное — разобранный адрес, ФИАС, КЛАДР, почтовый индекс, часовой пояс —
 * сознательно игнорируется: это персональные данные и справочные сведения,
 * которые логистике не нужны, а хранить их пришлось бы наравне с адресом.
 *
 * Сырой ответ не сохраняется нигде: из него извлекаются координаты и признак
 * точности, всё остальное умирает вместе с переменной.
 */

import { z } from 'zod';

/**
 * Точность определения координат.
 *
 * Официальные значения `qc_geo`: 0 — точные координаты дома, 1 — ближайший дом,
 * 2 — улица, 3 — населённый пункт, 4 — город, 5 — координаты не определены.
 * Точкой доставки считается только 0. «Ближайший дом» — это уже чужой подъезд,
 * а иногда и другая сторона улицы: курьер поедет не туда, а данные при этом
 * будут выглядеть нормальными.
 */
export const QC_GEO_EXACT = 0;

/** Числа приходят строками: JSON DaData отдаёт координаты и qc_geo текстом. */
const numeric = z.union([z.string(), z.number()]).nullable().optional();

export const dadataAddressSchema = z.object({
  geo_lat: numeric,
  geo_lon: numeric,
  qc_geo: numeric,
});

/**
 * Проверенный результат.
 *
 * Поля необязательны намеренно: отсутствие координаты — обычный ответ DaData
 * для адреса, который она не смогла привязать, а не повод считать ответ битым.
 */
export type DadataAddress = z.infer<typeof dadataAddressSchema>;

/**
 * Приводит `qc_geo` к целому числу.
 *
 * Отсутствующее или нечисловое значение — не повод считать точку точной:
 * возвращается `null`, и вызывающая сторона отправляет заказ на проверку.
 */
export function parseQcGeo(value: string | number | null | undefined): number | null {
  if (typeof value === 'number') {
    return Number.isInteger(value) ? value : null;
  }
  if (typeof value !== 'string' || !/^\d+$/.test(value.trim())) {
    return null;
  }
  return Number(value.trim());
}
