/**
 * Предел одного расчёта матрицы — в одном месте на всё приложение.
 *
 * Число появилось не из осторожности, а из измерения: первый операционный пилот
 * на настоящем графе получил от Valhalla `400 Exceeded max locations: 2500` на
 * дне из 60 точек. Приложение разрешало 60, конфигурация графа — 2500 пар,
 * то есть 50×50. Два числа жили в разных файлах и разъехались молча.
 *
 * Поэтому источник ровно один — `tools/geo/graph-limits.json`, а здесь
 * его runtime-форма. Совпадение доказывает направленный тест: файл сборки
 * графа читает JSON напрямую, приложение — эти константы, и разойтись им
 * тест не даёт.
 *
 * Число ПАР отдельным значением не хранится нигде: матрица квадратная,
 * и `pairs = points²` — не соглашение, а определение.
 */

/** Предел уникальных точек одного расчёта, включая склад. */
export const MAX_MATRIX_POINTS = 60;

/**
 * Бюджет маршрутизатора на один запрос матрицы.
 *
 * Valhalla считает не точки, а маршруты: `service_limits.<профиль>
 * .max_matrix_location_pairs`. Квадратная матрица на 60 точках стоит 3600
 * маршрутов, и меньший бюджет отвергает её целиком — не деградацией, а 400.
 */
export const MAX_MATRIX_LOCATION_PAIRS = MAX_MATRIX_POINTS * MAX_MATRIX_POINTS;

/** Профили, которыми пользуется приложение. Бюджет обязателен обоим. */
export const MATRIX_PROFILES = ['auto', 'pedestrian'] as const;
