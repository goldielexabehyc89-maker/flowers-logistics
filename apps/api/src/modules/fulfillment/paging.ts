/**
 * Страница производственного списка.
 *
 * День мастерской вырос до сотни с лишним заказов, и отдавать его одним ответом
 * стало нечестно: клиент получает килобайты, которых не показывает, а браузер
 * строит сотни узлов DOM, из которых человек видит десяток.
 *
 * ГЛАВНОЕ ПРАВИЛО: СНАЧАЛА ПОРЯДОК, ПОТОМ СРЕЗ.
 *
 * Обрезать выборку в SQL и сортировать уже обрезанное запрещено. Порядок
 * очереди флориста групповой: сначала целиком самый ранний подтверждённый
 * маршрутный лист, затем следующий, и только потом обычная срочность
 * (`queue.ts`). Взять из базы «первые 50 по времени» и упорядочить их — значит
 * потерять из выборки заказы раннего маршрута с поздним собственным временем
 * и поднять на их место заказы позднего маршрута. Флорист получил бы два
 * наполовину собранных листа вместо одного готового — то есть ровно тот
 * дефект, ради предотвращения которого правило и написано.
 *
 * Поэтому `takePage` принимает УЖЕ упорядоченный список целиком и режет его
 * в памяти. День ограничен физической пропускной способностью мастерской:
 * это сотни строк, а не миллионы, и полный проход по ним дешевле, чем
 * недоказуемый групповой подзапрос.
 *
 * ГДЕ СРЕЗ В SQL ДОПУСТИМ. Только там, где порядок полный и выражается самой
 * базой без группового правила, — так устроена очередь печати (`print.ts`):
 * она упорядочена по времени создания с устойчивым добором по идентификатору,
 * и `skip`/`take` над таким порядком дают ровно ту же страницу, что и срез
 * в памяти. Такой список берёт из этого модуля только описание страницы
 * (`pageInfo`), а не `takePage`.
 */

/** Размер страницы по умолчанию: столько строк человек осматривает за раз. */
export const PAGE_SIZE_DEFAULT = 50;

/**
 * Наибольший размер страницы.
 *
 * Ограничение серверное, а не рекомендация клиенту: без него один запрос
 * с `limit=100000` вернул бы обратно весь день и обесценил бы весь срез.
 */
export const PAGE_SIZE_MAX = 100;

/** Что просит клиент. */
export interface PageRequest {
  limit: number;
  offset: number;
}

/** Что клиент обязан знать, чтобы честно показать продолжение. */
export interface PageInfo {
  /** Сколько строк во всей выборке, а не на странице. */
  total: number;
  limit: number;
  offset: number;
  /** Есть ли что показывать дальше. Считается сервером, а не клиентом. */
  hasMore: boolean;
}

/**
 * Приведение запроса к допустимым границам.
 *
 * Нормализация живёт здесь, а не только в схеме HTTP: очередь читают и
 * напрямую из проверок, и запрос без ограничений не должен зависеть от того,
 * через какой вход он пришёл.
 */
export function normalizePageRequest(request: Partial<PageRequest> | undefined): PageRequest {
  const limit = Math.trunc(request?.limit ?? PAGE_SIZE_DEFAULT);
  const offset = Math.trunc(request?.offset ?? 0);
  return {
    limit: Math.min(Math.max(Number.isFinite(limit) ? limit : PAGE_SIZE_DEFAULT, 1), PAGE_SIZE_MAX),
    offset: Math.max(Number.isFinite(offset) ? offset : 0, 0),
  };
}

/**
 * Описание страницы по фактически возвращённым строкам.
 *
 * `hasMore` считается по позиции конца страницы, а не по «набрали ли полный
 * limit»: последняя страница ровно в `limit` строк не должна обещать
 * продолжения, которого нет.
 */
export function pageInfo(request: PageRequest, total: number, returned: number): PageInfo {
  const normalized = normalizePageRequest(request);
  return {
    total,
    limit: normalized.limit,
    offset: normalized.offset,
    hasMore: normalized.offset + returned < total,
  };
}

/**
 * Страница уже упорядоченного списка.
 *
 * Вход обязан быть полным и упорядоченным каноническим правилом раздела:
 * функция только режет и ничего не сортирует. Смещение за пределами списка
 * даёт пустую страницу с честным `total`, а не ошибку — так клиент, отставший
 * от изменившейся очереди, получает понятный ответ и перезапрашивает первую
 * страницу.
 */
export function takePage<T>(
  ordered: readonly T[],
  request: Partial<PageRequest> | undefined,
): PageInfo & { items: T[] } {
  const normalized = normalizePageRequest(request);
  const items = ordered.slice(normalized.offset, normalized.offset + normalized.limit);
  return { items, ...pageInfo(normalized, ordered.length, items.length) };
}
