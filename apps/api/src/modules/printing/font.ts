/**
 * Шрифт этикеток.
 *
 * КИРИЛЛИЦА. Встроенные шрифты PDF её не содержат вовсе, а встроенные шрифты
 * термопринтера — тем более: код ячейки «СТЕЛЛАЖ-A-001» напечатался бы
 * вопросительными знаками. Поэтому и бумага, и растр для принтера рисуются
 * ОДНИМ файлом шрифта, приходящим зависимостью npm, а не тянущимся с CDN:
 * этикетка обязана печататься на машине без интернета.
 *
 * Один и тот же шрифт для PDF и для растра — не экономия, а требование:
 * иначе предпросмотр на экране и наклейка из принтера отличались бы шириной
 * строки, и подобранный по PDF кегль не помещался бы на ленте.
 */

import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

/**
 * Путь разрешается через `require.resolve`, а не собирается из `node_modules`
 * руками: расположение пакета зависит от того, как менеджер пакетов разложил
 * дерево, и склеенный путь однажды перестал бы находиться.
 */
const resolveFromHere = createRequire(import.meta.url);

let cache: Uint8Array | null = null;

/**
 * Байты шрифта. Читаются один раз за процесс: файл около 750 КБ, и перечитывать
 * его на каждую печать значит тратить время на данные, которые не меняются.
 */
export function labelFontBytes(): Uint8Array {
  if (cache === null) {
    cache = new Uint8Array(
      readFileSync(resolveFromHere.resolve('dejavu-fonts-ttf/ttf/DejaVuSans.ttf')),
    );
  }
  return cache;
}
