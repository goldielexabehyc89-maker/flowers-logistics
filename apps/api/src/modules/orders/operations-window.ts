/**
 * Начало операционной работы: фиксированная граница даты доставки.
 *
 * Разовое переключение: рабочие списки («Самовывоз», очередь флориста,
 * «Логистика → Сделки») показывают заказы с датой доставки ОТ этого дня
 * включительно. Заказы более ранних дней (в т.ч. 29.08.2026) из рабочих
 * выдач исключаются на серверном уровне, чтобы не возвращаться после realtime
 * или следующей синхронизации.
 *
 * Это НЕ динамическое «прятать сегодняшний день»: граница фиксированная. Для
 * production и staging она именно эта — переменную окружения там не задают,
 * поэтому поведение общее и предсказуемое. Ослабляется значение лишь ради
 * изоляции проверок (браузерный smoke и серверный стенд заводят синтетические
 * заказы текущим днём) — через `config.OPERATIONS_START_DATE`, который по
 * умолчанию равен этой константе. Заказы физически не удаляются, их данные и
 * статусы не меняются, в «Истории заказов» они по-прежнему находятся для аудита.
 *
 * Дата — московская календарная (`ГГГГ-ММ-ДД`); колонка `deliveryDate`
 * хранит именно московский календарный день. Заказы без даты доставки границей
 * не отсекаются: у них нет дня, который можно было бы назвать «до 30.08».
 *
 * Значение по умолчанию. Отборы принимают эффективную границу параметром
 * (маршруты передают `config.OPERATIONS_START_DATE`); прямые вызовы без него
 * берут этот же день, поэтому серверные проверки границы доказывают именно
 * продакшн-поведение.
 */
export const OPERATIONS_START_DATE = '2026-08-30';
