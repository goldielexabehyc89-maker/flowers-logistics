/**
 * Идентичность заказа снимка.
 *
 * Колонка `externalId` имеет тип UUID, а ключ снимка им не является. Поэтому
 * ключ нужно во что-то отобразить — и от того, КАК он отображается, зависит,
 * останутся ли два разных заказа двумя заказами.
 *
 * Прежняя схема брала первые 16 символов ключа и переписывала их байты
 * в шестнадцатеричном виде. Для ключей штатного экспортёра (`order-` плюс
 * десять шестнадцатеричных цифр — ровно 16 символов) она работала, но
 * инвариантом это не было нигде: ни формат `orders-snapshot@2`, ни документация
 * длину ключа не ограничивают. Десять ключей вида `syn-2026-08-20-NN`
 * различаются семнадцатым символом и давали ДВА идентификатора на десять
 * заказов — девять записей молча слились в одну, а импорт отчитался успехом.
 * Такое поведение противоречит правилу «отказ лучше частичного импорта»,
 * на котором построен весь модуль снимков.
 *
 * Здесь ключ участвует ЦЕЛИКОМ.
 *
 * Алгоритм — UUID версии 5 (RFC 9562 §5.5): SHA-1 от байтов пространства имён
 * и полного имени, из которых берутся первые 16 байт, а биты версии и варианта
 * проставляются по стандарту. Свой формат не изобретается: name-based UUID
 * существует ровно для этой задачи, воспроизводится любой библиотекой в любом
 * языке и не зависит от того, каким процессом посчитан.
 *
 * SHA-1 здесь не криптографическая защита, а способ детерминированно свернуть
 * имя: восстановить ключ по идентификатору не нужно никому, а подделывать его
 * некому — снимок и так проверяется отдельными воротами.
 *
 * ИМЕНЕМ СЛУЖИТ ТОЛЬКО КЛЮЧ.
 *
 * Ни версия формата файла, ни дата снимка, ни его имя в имя UUID не входят.
 * Иначе тот же заказ, выгруженный завтра или в формате `@3`, получил бы другой
 * идентификатор, и повторный импорт создал бы вторую копию вместо обновления
 * первой. Совместимость формата — отдельный вопрос от идентичности заказа.
 */

import { createHash } from 'node:crypto';
import {
  SnapshotSafetyError,
  type OrdersSnapshot,
  type SnapshotOrder,
} from '../snapshot-export.js';

/**
 * Пространство имён идентичности заказа снимка.
 *
 * Постоянная величина, привязанная к смыслу «заказ синтетического снимка
 * flowers-logistics», а не к файлу, дате или версии формата. Получена
 * стандартным способом — UUIDv5 в пространстве URL (RFC 9562, приложение A)
 * от имени `https://flowers-logistics.invalid/snapshot/order-identity`:
 *
 *   uuid5(6ba7b811-9dad-11d1-80b4-00c04fd430c8,
 *         'https://flowers-logistics.invalid/snapshot/order-identity')
 *
 * Домен `.invalid` выбран намеренно: он зарезервирован RFC 2606 и никому
 * не принадлежит, поэтому пространство имён не станет чужим вместе с доменом.
 *
 * Значение записано литералом, а не вычисляется при старте: пространство имён —
 * долгоживущий договор, и его изменение сменило бы идентичность ВСЕХ заказов
 * всех снимков разом. Литерал вместе с закрепляющим его тестом делает такую
 * смену видимой в diff, а не следствием правки строки-имени.
 */
export const ORDER_IDENTITY_NAMESPACE = 'c195b54b-2cef-504d-9015-53cb3ef97adf';

/** Шестнадцать байт UUID из его текстовой записи. */
function uuidBytes(value: string): Buffer {
  return Buffer.from(value.replace(/-/g, ''), 'hex');
}

/**
 * UUIDv5 от полного имени.
 *
 * Отдельная функция, потому что пространство имён — параметр стандарта,
 * а не константа алгоритма: так значение `ORDER_IDENTITY_NAMESPACE`
 * проверяется тестом через тот же код, которым пользуется импорт.
 */
export function uuidV5(namespace: string, name: string): string {
  const digest = createHash('sha1')
    .update(uuidBytes(namespace))
    .update(Buffer.from(name, 'utf8'))
    .digest();

  const bytes = digest.subarray(0, 16);
  // Версия 5 в старших четырёх битах седьмого байта.
  bytes[6] = ((bytes[6] as number) & 0x0f) | 0x50;
  // Вариант RFC 9562 (10xx) в старших битах девятого байта.
  bytes[8] = ((bytes[8] as number) & 0x3f) | 0x80;

  const hex = bytes.toString('hex');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    hex.slice(12, 16),
    hex.slice(16, 20),
    hex.slice(20, 32),
  ].join('-');
}

/**
 * Идентичность заказа снимка по его ключу.
 *
 * Единственный способ получить `externalId` из ключа. Импорт, вывод из области
 * и восстановление обязаны звать именно её: два способа считать идентичность
 * однажды разойдутся, и разойдутся молча.
 */
export function orderIdentity(key: string): string {
  return uuidV5(ORDER_IDENTITY_NAMESPACE, key);
}

/**
 * Как ключ отображается в идентификатор. Параметр существует ради теста
 * искусственной коллизии: подменить его в бою нечем — вызовы `resolveIdentities`
 * в импорте и выводе из области второго аргумента не передают.
 */
export type IdentityMapper = (key: string) => string;

/**
 * Ворота идентичности. Выполняются ДО транзакции и до любой записи.
 *
 * Порядок проверок не случаен: сначала сам ключ, потом его повтор в снимке,
 * и только потом отображение. Ошибка в обратном порядке рассказывала бы про
 * коллизию идентификаторов там, где на деле дважды приехал один ключ.
 *
 * Ни одно сообщение не содержит ключа, псевдонима, адреса или номера заказа —
 * только код, причина и порядковый номер записи в файле. Номер позволяет
 * дежурному найти строку в своём файле и ничего не сообщает о данных тому,
 * кто файла не видел.
 */
export interface IdentifiedOrder {
  order: SnapshotOrder;
  externalId: string;
}

export function resolveIdentities(
  snapshot: OrdersSnapshot,
  mapper: IdentityMapper = orderIdentity,
): IdentifiedOrder[] {
  const seenKeys = new Set<string>();
  const owners = new Map<string, number>();
  const resolved: IdentifiedOrder[] = [];

  for (const [index, order] of snapshot.orders.entries()) {
    const position = index + 1;
    const key: unknown = order.key;

    if (typeof key !== 'string' || key.trim() === '') {
      throw new SnapshotSafetyError(
        'SNAPSHOT_KEY_INVALID',
        `Запись ${position}: ключ заказа пуст или не является строкой`,
      );
    }
    if (seenKeys.has(key)) {
      throw new SnapshotSafetyError(
        'SNAPSHOT_DUPLICATE_KEY',
        `Запись ${position}: этот ключ уже встречался в снимке`,
      );
    }

    const externalId = mapper(key);
    const owner = owners.get(externalId);

    if (owner !== undefined) {
      throw new SnapshotSafetyError(
        'SNAPSHOT_IDENTITY_COLLISION',
        `Записи ${owner} и ${position} с разными ключами дали один идентификатор`,
      );
    }

    seenKeys.add(key);
    owners.set(externalId, position);
    resolved.push({ order, externalId });
  }

  return resolved;
}
