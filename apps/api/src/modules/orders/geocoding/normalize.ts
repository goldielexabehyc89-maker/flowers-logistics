/**
 * Нормализованный адрес — ключ кэша геокодирования.
 *
 * Один и тот же адрес приходит из МоегоСклада в десятке написаний: разный
 * регистр, лишние пробелы, «ул.» и «улица», «д.5» и «дом 5». Без приведения
 * к общей форме кэш почти не срабатывал бы, и мы отправляли бы в геокодер
 * отдельный запрос за каждую опечатку.
 *
 * Нормализация НЕ используется для показа человеку и не заменяет адрес
 * в заказе: это исключительно ключ. Поэтому она может быть агрессивной —
 * потеря красоты записи здесь ничего не стоит.
 *
 * Границы слов заданы явными просмотрами, а не `\b`. В JavaScript `\w` — это
 * только латиница, цифры и подчёркивание, поэтому `\b` рядом с кириллицей
 * ставится не там, где ожидается: `\bул\b` не находит «ул» в «ул. Тверская»
 * вовсе. Первая версия этого файла именно так и не разворачивала ни одного
 * сокращения — молча, потому что результат оставался правдоподобным.
 */

/** Буква или цифра любого из используемых алфавитов. */
const WORD = '0-9a-zа-я';

/** Сокращение, стоящее отдельным словом: «ул.» → «улица». */
function word(pattern: string, replacement: string): readonly [RegExp, string] {
  return [new RegExp(`(?<![${WORD}])(?:${pattern})\\.?(?![${WORD}])`, 'g'), replacement];
}

/** Сокращение перед числом: «д.5» и «д. 5» → «дом 5». */
function beforeNumber(pattern: string, replacement: string): readonly [RegExp, string] {
  return [new RegExp(`(?<![${WORD}])(?:${pattern})\\.?\\s*(?=\\d)`, 'g'), `${replacement} `];
}

/**
 * Сокращения, приводимые к одной форме.
 *
 * Порядок имеет значение: правила «перед числом» должны стоять раньше правил
 * «отдельным словом», иначе «к» в «к.2» успело бы стать чем-то другим.
 */
const ABBREVIATIONS: ReadonlyArray<readonly [RegExp, string]> = [
  beforeNumber('дом|д', 'дом'),
  beforeNumber('корпус|корп|кор|к', 'корпус'),
  beforeNumber('строение|стр', 'строение'),
  beforeNumber('квартира|кв', 'квартира'),
  beforeNumber('офис|оф', 'офис'),
  beforeNumber('владение|влд|вл', 'владение'),

  word('улица|ул', 'улица'),
  word('проспект|пр-кт|пр-т|просп|пр', 'проспект'),
  word('переулок|пер', 'переулок'),
  word('шоссе|шос|ш', 'шоссе'),
  word('набережная|наб', 'набережная'),
  word('бульвар|б-р|бул', 'бульвар'),
  word('площадь|пл', 'площадь'),
  word('проезд|пр-д', 'проезд'),
  word('город|гор|г', 'город'),
  word('посёлок|поселок|пос|п', 'поселок'),
  word('деревня|дер|д', 'деревня'),
  word('область|обл', 'область'),
  word('район|р-н|рн', 'район'),
];

/**
 * Ключ кэша по адресу.
 *
 * Пустая строка означает «ключа нет»: пустой адрес нельзя ни искать,
 * ни кэшировать.
 */
export function normalizeAddress(raw: string | null | undefined): string {
  if (raw === null || raw === undefined) {
    return '';
  }

  let value = raw.toLowerCase();

  // Ё и е в адресах пишут вперемешку, и это один и тот же адрес.
  value = value.replace(/ё/g, 'е');

  // Разделители приводятся к пробелу: «Москва,ул.Тверская» и
  // «Москва, ул. Тверская» — одна строка.
  value = value.replace(/[,;]/g, ' ');

  for (const [pattern, replacement] of ABBREVIATIONS) {
    value = value.replace(pattern, replacement);
  }

  // Всё, кроме букв, цифр и пробела, роли ключа не играет.
  value = value.replace(/[^0-9a-zа-я\s]/g, ' ');

  return value.split(/\s+/).filter(Boolean).join(' ');
}
