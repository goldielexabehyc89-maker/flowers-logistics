/**
 * Кто и когда имеет право обращаться к внешним адресным сервисам.
 *
 * Сервисов теперь два, и у них РАЗНЫЕ правила — потому что это разные риски:
 *
 * 1. **Photon** — наш собственный, поднятый нами, работает офлайн. Обращение
 *    к нему не стоит денег и не отдаёт адрес третьей стороне, поэтому
 *    единственное условие — он настроен. Именно он и только он геокодирует
 *    новые и изменённые адреса автоматически.
 * 2. **DaData Suggestions** — чужой платный сервис. Каждый запрос содержит
 *    адрес клиента и расходует квоту организации, поэтому условий три:
 *    разрешённое окружение (оба признака совпали), явное включение и ключ.
 *    Подсказки используются ТОЛЬКО в ручной правке адреса.
 *
 * Платный `Clean API` DaData не вызывается нигде: автоматическое
 * геокодирование делает Photon (`docs/OWNER_DECISIONS.md`, `GEO-005`).
 */

import { dadataEnvironment, type AppConfig } from '../../../platform/config.js';

/**
 * Разрешены ли подсказки DaData.
 *
 * Только ручная правка адреса. Ни один фоновый проход их не вызывает:
 * подсказка нужна человеку, который печатает, а не обходу очереди.
 *
 * Ключ ровно один: подсказки авторизуются заголовком `Authorization: Token`.
 * Секретный ключ требовался платному Clean API, которого больше нет.
 */
export function isDadataAllowed(config: AppConfig): boolean {
  return (
    dadataEnvironment(config) !== 'denied' &&
    config.DADATA_GEOCODING_ENABLED &&
    config.DADATA_API_KEY !== undefined
  );
}

/**
 * Настроен ли собственный Photon.
 *
 * Отсутствие адреса — не ошибка, а честное «геокодер не настроен»: список
 * продолжает работать по данным базы, а новые адреса остаются
 * в «Требует внимания» и в маршрутизацию не допускаются.
 */
export function isPhotonConfigured(config: AppConfig): boolean {
  const url = config.PHOTON_URL;
  return url !== undefined && url.trim() !== '';
}

/**
 * Выполняется ли автоматическое геокодирование.
 *
 * Раньше это решал DaData и его окружение; теперь — наличие собственного
 * Photon. Окружение здесь не участвует намеренно: свой сервис одинаково
 * допустим и в staging, и в production, потому что не тратит чужих денег
 * и не отдаёт адреса наружу.
 */
export function shouldGeocodeAutomatically(config: AppConfig): boolean {
  return isPhotonConfigured(config);
}
