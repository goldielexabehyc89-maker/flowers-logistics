/**
 * Условия обращения к живому DaData.
 *
 * Вынесено отдельными функциями, чтобы правило можно было проверить тестом
 * напрямую, не поднимая приложение: «не обращаемся к платному сервису там, где
 * не разрешено» — это не деталь запуска, а обещание, которое нужно доказывать.
 *
 * Условий три и они обязаны выполниться одновременно: разрешённое окружение
 * (оба признака совпали), явное включение и фактическое наличие ОБОИХ ключей.
 * Каждое закрывает свою ошибку развёртывания.
 *
 * Владелец разрешил staging наравне с production (`docs/OWNER_DECISIONS.md`,
 * `GEO-004`). Ключи по-прежнему живут только в приватной конфигурации сервера
 * и в браузер не попадают ни в каком виде.
 */

import { dadataEnvironment, type AppConfig } from '../../../platform/config.js';

/** Есть ли полная пара ключей. Половина пары — ошибка, а не частичный доступ. */
function hasBothKeys(config: AppConfig): boolean {
  return config.DADATA_API_KEY !== undefined && config.DADATA_SECRET_KEY !== undefined;
}

/**
 * Разрешено ли этому процессу обращаться к DaData вообще.
 *
 * Одно правило на все обращения: и на фоновое геокодирование, и на подсказки
 * адреса. Иначе подсказки однажды оказались бы разрешены там, где геокодирование
 * запрещено, — при том что наружу уходит один и тот же адрес клиента.
 */
export function isDadataAllowed(config: AppConfig): boolean {
  return (
    dadataEnvironment(config) !== 'denied' && config.DADATA_GEOCODING_ENABLED && hasBothKeys(config)
  );
}

/**
 * Разрешено ли фоновое автоматическое геокодирование.
 *
 * Совпадает с общим правилом: отдельного «тихого» режима, в котором фоновый
 * обход ходил бы в сеть без разрешения подсказкам, не существует.
 */
export function shouldGeocodeAutomatically(config: AppConfig): boolean {
  return isDadataAllowed(config);
}
