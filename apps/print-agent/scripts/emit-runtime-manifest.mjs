/**
 * Кладёт рядом со сборкой манифест времени выполнения.
 *
 * ЗАЧЕМ. Установщик копирует содержимое `dist` в каталог профиля пользователя —
 * вне репозитория и вне рабочей области npm. Вид модулей Node определяет по
 * ближайшему `package.json`, а там его больше нет. Сборка состоит из ESM,
 * и без явного `"type": "module"` всё держится на автоматическом распознавании
 * синтаксиса, которое включено по умолчанию только с Node 22.7.
 *
 * Установщик же допускает Node 20 — сознательно, чтобы не требовать
 * обновления там, где всё остальное работает. Ровно на нём распознавания нет,
 * и первый же `import` упал бы с `Cannot use import statement outside a
 * module`: только на машине владельца, только после установки и без единой
 * подсказки о причине — в репозитории-то запускается.
 *
 * Полагаться на распознавание не стоит и на новых версиях: это запасной путь
 * для файлов без объявленного вида, а не способ его объявить.
 *
 * Манифест намеренно минимальный. Копировать сюда `package.json` рабочей
 * области нельзя: в нём остались бы `scripts` со ссылками на `tsc`, которого
 * на компьютере флориста нет, и `main`, указывающий на `./dist/main.js` —
 * путь, которого после установки не существует.
 */

import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const distDir = join(packageRoot, 'dist');

const manifest = {
  name: 'florist-print-agent',
  private: true,
  // Единственная строка, ради которой всё это существует.
  type: 'module',
  main: './main.js',
};

await writeFile(join(distDir, 'package.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
