/**
 * Общая низкоуровневая часть карт: воркер MapLibre и протокол PMTiles.
 *
 * Вынесена сюда потому, что и то, и другое настраивается ОДИН РАЗ НА ПРИЛОЖЕНИЕ,
 * а карт в приложении две — маршруты и сделки. Повторная регистрация протокола
 * `pmtiles://` в MapLibre считается ошибкой, и второй экран, объявивший её
 * у себя, ронял бы первый. Флаг, живущий внутри одного модуля, второй модуль
 * не видит, поэтому «по флагу в каждом файле» здесь не работает.
 *
 * Поведение не изменилось: это ровно то, что раньше стояло в `OrdersMap.tsx`.
 */

import { addProtocol, setWorkerUrl } from 'maplibre-gl';
import { Protocol } from 'pmtiles';
// Воркер собирается отдельным файлом, и его адрес известен сборщику.
import maplibreWorkerUrl from 'maplibre-gl/dist/maplibre-gl-worker.mjs?worker&url';

/**
 * Адрес воркера MapLibre.
 *
 * Разбор векторных тайлов идёт в веб-воркере. Свой адрес MapLibre вычисляет
 * от `import.meta.url` собственного модуля: в собранном приложении это
 * `/assets/<чанк>.js`, и получается `/assets/maplibre-gl-worker.mjs` — файла
 * с таким именем сборка не создаёт. Одностраничное приложение отвечает на этот
 * адрес своей оболочкой, воркер получает HTML вместо кода и молча не отвечает.
 *
 * Видимых следов у поломки нет: стиль применяется, заголовок архива тайлов
 * скачивается, ошибок в консоли не появляется — но тайлы не разбираются
 * никогда, и карта навсегда остаётся в состоянии загрузки.
 *
 * Поэтому адрес задаётся явно и берётся у сборщика. Вызов на уровне модуля
 * не случаен — он обязан произойти до создания первой карты, иначе пул
 * воркеров успеет подняться с неверным адресом.
 */
setWorkerUrl(maplibreWorkerUrl);

/** Москва: обе карты открываются там, где работает служба. */
export const DEFAULT_CENTER: [number, number] = [37.6173, 55.7558];
export const DEFAULT_ZOOM = 10;

let pmtilesRegistered = false;

/** Регистрирует протокол `pmtiles://` ровно один раз на приложение. */
export function registerPmtiles(): void {
  if (pmtilesRegistered) {
    return;
  }
  const protocol = new Protocol();
  addProtocol('pmtiles', protocol.tile);
  pmtilesRegistered = true;
}
